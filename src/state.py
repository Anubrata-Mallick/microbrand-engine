from typing import TypedDict, List, Dict, Any, Optional

class BrandProfile(TypedDict):
    brand_name: str
    tone: List[str]            # e.g., ["minimalist", "playful", "eco-conscious"]
    forbidden_words: List[str] # words the brand never uses (e.g., ["cheap", "guarantee"])
    target_audience: str       # e.g., "Gen Z urban commuters"
    signature_phrase: str      # optional tagline or footer phrase

class AgentState(TypedDict):
    # Inputs
    brand_id: str
    product_title: str
    product_features: List[str]
    target_platforms: List[str] # e.g., ["instagram", "shopify", "amazon"]

    # Memory state
    brand_profile: Optional[BrandProfile]

    # Outputs generated by nodes
    generated_copies: Dict[str, str]
    critique_feedback: Optional[str]
    is_approved: bool

    # Execution trace
    logs: List[str]